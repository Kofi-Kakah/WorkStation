/**
 * Seed data for the WorkStation demo workspace.
 *
 * The three product modules share one dataset:
 *  - Jira-style issues are the canonical work items.
 *  - Trello-style boards are views over those issues (a card is an issue).
 *  - Slack-style channels reference issues and can spawn them from messages.
 *
 * Timestamps are generated once relative to module load so the feed always
 * looks "live" in a fresh browser session.
 */

