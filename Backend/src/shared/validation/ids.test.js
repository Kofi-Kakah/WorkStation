import { describe, expect, it } from "vitest";
import { idSchema, isSafeId } from "./ids.js";

describe("safe identifier validation", () => {
  it("accepts IDs generated by the application and Firebase", () => {
    expect(idSchema.parse("0f8fad5b-d9cb-469f-a165-70867728950e")).toBe(
      "0f8fad5b-d9cb-469f-a165-70867728950e",
    );
    expect(isSafeId("dm_5f3c9a")).toBe(true);
    expect(isSafeId("AbC123")).toBe(true);
  });

  it("rejects path traversal and separators", () => {
    for (const value of [
      "../users/owner",
      "a/b",
      "..",
      ".",
      "",
      "has space",
      "line\nbreak",
      "a".repeat(129),
    ]) {
      expect(idSchema.safeParse(value).success).toBe(false);
      expect(isSafeId(value)).toBe(false);
    }
  });
});
